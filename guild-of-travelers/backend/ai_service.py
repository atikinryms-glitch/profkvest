# AI Service for analyzing free-form answers
# Uses keyword-based analysis (can be extended with YandexGPT/GigaChat API)

def analyze_answer(answer_text: str) -> dict:
    """
    Анализирует ответ и возвращает баллы по типам Климова:
    Ч-П (Человек-Природа)
    Ч-Т (Человек-Техника)
    Ч-Х (Человек-Художественный образ)
    Ч-Ч (Человек-Человек)
    Ч-З (Человек-Знаковая система)
    """
    
    scores = {"Ч-П": 0, "Ч-Т": 0, "Ч-Х": 0, "Ч-Ч": 0, "Ч-З": 0}
    answer_lower = answer_text.lower()
    
    # Ключевые слова для каждого типа профессий
    nature_words = [
        'природ', 'лес', 'растен', 'животн', 'эколог', 'дерев', 'земл', 
        'ферм', 'сад', 'огород', 'цветы', 'почв', 'климат', 'ландшафт',
        'биолог', 'ботан', 'зоолог', 'агроном', 'геолог', 'охран'
    ]
    
    tech_words = [
        'механизм', 'техник', 'инженер', 'созда', 'постро', 'инструмент', 
        'устройств', 'компьютер', 'код', 'программ', 'робот', 'машин',
        'конструк', 'архитект', 'дизайн технич', 'сборк', 'ремонт',
        'электрон', 'схем', 'детал', 'узл', 'агрегат', 'автомат'
    ]
    
    art_words = [
        'творчеств', 'искусств', 'музык', 'литератур', 'дизайн', 
        'рисован', 'песн', 'стих', 'красот', 'худож', 'писатель',
        'актер', 'режиссер', 'компози', 'танец', 'театр', 'кино',
        'фотограф', 'скульптор', 'архитект худож', 'мода', 'стиль',
        'воображен', 'фантаз', 'креатив', 'вдохнов'
    ]
    
    people_words = [
        'люд', 'общен', 'помощ', 'обучен', 'медицин', 'учитель', 
        'врач', 'забот', 'команд', 'коллектив', 'клиент', 'пациент',
        'воспит', 'тренер', 'психолог', 'социальн', 'продаж', 'сервис',
        'переговор', 'поддерж', 'руковод', 'менеджер', 'организац'
    ]
    
    info_words = [
        'информац', 'анализ', 'числ', 'данны', 'текст', 'математ', 
        'логик', 'систем', 'программ', 'код', 'алгоритм', 'форму',
        'таблиц', 'график', 'диаграмм', 'статист', 'бухгалт', 'эконом',
        'язык', 'перевод', 'секретар', 'делопроизвод', 'картограф',
        'вычисл', 'контрол', 'провер', 'монитор'
    ]
    
    # Подсчёт баллов по ключевым словам
    for word in nature_words:
        if word in answer_lower:
            scores["Ч-П"] += 1
    
    for word in tech_words:
        if word in answer_lower:
            scores["Ч-Т"] += 1
    
    for word in art_words:
        if word in answer_lower:
            scores["Ч-Х"] += 1
    
    for word in people_words:
        if word in answer_lower:
            scores["Ч-Ч"] += 1
    
    for word in info_words:
        if word in answer_lower:
            scores["Ч-З"] += 1
    
    # Ограничение максимум 3 баллами (чтобы соответствовать готовым вариантам)
    for key in scores:
        scores[key] = min(scores[key], 3)
    
    # Если все нули — равномерное распределение с небольшим смещением к Ч-Ч
    if sum(scores.values()) == 0:
        scores = {"Ч-П": 1, "Ч-Т": 1, "Ч-Х": 1, "Ч-Ч": 2, "Ч-З": 1}
    
    return scores


